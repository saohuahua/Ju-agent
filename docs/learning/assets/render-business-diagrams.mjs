// 泳道图以时间从上到下排列 每条横线是一项业务交接
function swim(id,title,subtitle,rows,footer) {
  const labels=['客户与页面','会话与业务受理','后台与领域记录','主管或操作员']
  const xs=[35,310,585,860], w=225, height=200+rows.length*133
  const groups=labels.map((label,i)=>({x:xs[i]-10,y:105,w:245,h:height-170,label,fill:i%2?'#f0f4f7':'#f3f6f8'}))
  const nodes=[], edges=[]
  rows.forEach((row,i)=> {
    const y=155+i*133
    nodes.push(node(xs[row.from],y,w,80,row.title,row.lines||[],row.fill||blue))
    if (row.to!==undefined && row.to!==row.from) {
      const yy=y+105, x1=xs[row.from]+w/2, x2=xs[row.to]+w/2
      edges.push(edge(`M${x1} ${y+80}V${yy}H${x2}`,row.label,(x1+x2)/2,yy-6))
    }
    if (i && rows[i-1].from===row.from && !row.branch) edges.push(edge(`M${xs[row.from]+w/2} ${y-(rows[i-1].to===undefined?53:28)}V${y}`))
    if (row.branch) edges.push(edge('M810 727H835V993H810','响应不明确',900,760))
  })
  add(id,title,subtitle,height,nodes,edges,groups,footer)
}
